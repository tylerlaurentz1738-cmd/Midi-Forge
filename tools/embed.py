# Turns tools/factory_model.txt into Source/core/DefaultModel.h (split into chunks so MSVC accepts it).
import os
here = os.path.dirname(os.path.abspath(__file__))
text = open(os.path.join(here, 'factory_model.txt')).read()
lines, chunks, cur = text.splitlines(True), [], ''
for l in lines:
    if len(cur) + len(l) > 12000: chunks.append(cur); cur = ''
    cur += l
chunks.append(cur)
out = ['#pragma once', '// Generated by tools/embed.py from tools/factory_model.txt. Do not edit by hand.', '#include <string>', 'namespace mf {', 'inline std::string defaultModelText()', '{', '    static const char* const parts[] = {']
out += ['        R"MF(' + c + ')MF",' for c in chunks]
out += ['    };', '    std::string s;', '    for (auto* p : parts) s += p;', '    return s;', '}', '}']
open(os.path.join(here, '..', 'Source', 'core', 'DefaultModel.h'), 'w').write('\n'.join(out) + '\n')
print(len(chunks), 'chunks', len(text), 'bytes')
